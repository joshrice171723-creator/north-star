const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktopShell', {
  navigateAcademy: (url) => ipcRenderer.invoke('academy:navigate', url),
  captureAcademyPage: () => ipcRenderer.invoke('academy:capture-page'),
  getAcademyCaptures: () => ipcRenderer.invoke('academy:get-captures'),
  deleteAcademyCapture: (id) => ipcRenderer.invoke('academy:delete-capture', id),
  getAcademyStudyMaterials: () => ipcRenderer.invoke('academy:get-study-materials'),
  generateAcademyFlashcards: (ids) => ipcRenderer.invoke('academy:generate-flashcards', ids),
  deleteAcademyStudyMaterial: (id) => ipcRenderer.invoke('academy:delete-study-material', id),
  getAcademyStudyReviews: () => ipcRenderer.invoke('academy:get-study-reviews'),
  setAcademyStudyReview: (id, status) => ipcRenderer.invoke('academy:set-study-review', id, status),
  openRouterChat: (messages, options) => ipcRenderer.invoke('openrouter:chat', messages, options),
  setAcademyVisible: (visible) => ipcRenderer.invoke('academy:set-visible', Boolean(visible)),
  setAcademyBounds: (bounds) => ipcRenderer.invoke('academy:set-bounds', bounds),
  coachBootstrap: () => ipcRenderer.invoke('coach:bootstrap'),
  syncRoadmap: (payload) => ipcRenderer.invoke('coach:sync-roadmap', payload),
  importRoadmap: (payload) => ipcRenderer.invoke('coach:import-roadmap', payload),
  saveNote: (content, title) => ipcRenderer.invoke('coach:save-note', content, title),
  backupDatabase: () => ipcRenderer.invoke('coach:backup'),
  listProjects: () => ipcRenderer.invoke('coach:projects:list'),
  listWorkspaces: () => ipcRenderer.invoke('coach:workspaces:list'),
  createWorkspace: (input) => ipcRenderer.invoke('coach:workspaces:create', input),
  updateWorkspace: (input) => ipcRenderer.invoke('coach:workspaces:update', input),
  deleteWorkspace: (id) => ipcRenderer.invoke('coach:workspaces:delete', id),
  createProject: (input) => ipcRenderer.invoke('coach:projects:create', input),
  updateProject: (input) => ipcRenderer.invoke('coach:projects:update', input),
  deleteProject: (id) => ipcRenderer.invoke('coach:projects:delete', id),
  listTasks: () => ipcRenderer.invoke('coach:tasks:list'),
  createTask: (input) => ipcRenderer.invoke('coach:tasks:create', input),
  updateTask: (input) => ipcRenderer.invoke('coach:tasks:update', input),
  deleteTask: (id) => ipcRenderer.invoke('coach:tasks:delete', id)
  ,listJobs: () => ipcRenderer.invoke('coach:jobs:list')
  ,createJob: (input) => ipcRenderer.invoke('coach:jobs:create', input)
  ,updateJob: (input) => ipcRenderer.invoke('coach:jobs:update', input)
  ,deleteJob: (id) => ipcRenderer.invoke('coach:jobs:delete', id)
  ,getJobProfile: () => ipcRenderer.invoke('jobs:profile:get')
  ,saveJobProfile: (input) => ipcRenderer.invoke('jobs:profile:save', input)
  ,getMasterResume: () => ipcRenderer.invoke('jobs:resume:get')
  ,saveMasterResume: (input) => ipcRenderer.invoke('jobs:resume:save', input)
  ,searchJobs: () => ipcRenderer.invoke('jobs:search')
  ,onJobSearchProgress: (listener) => { const handler = (_event, progress) => listener(progress); ipcRenderer.on('jobs:search:progress', handler); return () => ipcRenderer.removeListener('jobs:search:progress', handler); }
  ,getJobSource: () => ipcRenderer.invoke('jobs:source:get')
  ,saveJobSource: (input) => ipcRenderer.invoke('jobs:source:save', input)
  ,clearJobSource: () => ipcRenderer.invoke('jobs:source:clear')
  ,testJobSource: () => ipcRenderer.invoke('jobs:source:test')
  ,getJobSearchAttempts: (runId) => ipcRenderer.invoke('jobs:search:attempts', runId)
});
