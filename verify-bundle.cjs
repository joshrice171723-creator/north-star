const fs = require('fs');
const path = require('path');
const assets = path.join(__dirname, 'dist', 'assets');
const bundle = fs.readdirSync(assets).filter((f) => /^index-.*\.js$/.test(f)).map((f) => ({ name: f, full: path.join(assets, f), mtime: fs.statSync(path.join(assets, f)).mtime.toISOString() })).sort((a, b) => b.mtime.localeCompare(a.mtime))[0];
const t = fs.readFileSync(bundle.full, 'utf8');
const out = [];
out.push(`bundle=${bundle.name}`);
out.push(`mtime=${bundle.mtime}`);
out.push(`bytes=${t.length}`);
const oldBad = t.indexOf('return(0,C.useEffect)(()=>{if(!e||!t?.credential?.configured)return');
out.push(`oldInsideReturnPatternAt=${oldBad}`);
const count = (needle) => { let n = 0; let at = t.indexOf(needle); while (at >= 0) { n += 1; at = t.indexOf(needle, at + 1); } return n; };
out.push(`oldPatternCount=${count('return(0,C.useEffect)(()=>{if(!e||!t?.credential?.configured)return')}`);
out.push(`newHookCount=${count('(0,C.useEffect)(()=>{if(!e||!t?.credential?.configured)return')}`);
out.push(`activationStringCount=${count('Activation email matched')}`);
out.push(`twoSiteHandoffCount=${count('Two-site handoff')}`);
const hook = t.indexOf('(0,C.useEffect)(()=>{if(!e||!t?.credential?.configured)return');
out.push(`pollingHookAt=${hook}`);
const early = t.indexOf('if(!e||(!s&&');
out.push(`earlyReturnCandidateAt=${early}`);
const anchor = t.indexOf('window.__activeApplicationId');
out.push(`firstActiveAppIdAt=${anchor}`);
out.push(`contextAroundAnchor=${JSON.stringify(t.slice(Math.max(0, anchor - 80), anchor + 200))}`);
const failed = oldBad >= 0;
out.push(`verify=${failed ? 'FAIL_OLD_HOOK_ORDER_PRESENT' : 'PASS'}`);
fs.writeFileSync(path.join(__dirname, 'bundle-check-result.txt'), out.join('\n'));
process.exit(failed ? 1 : 0);
